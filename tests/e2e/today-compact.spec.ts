import { test, expect, type Page } from '@playwright/test'
import { createDenseToday } from '../fixtures/today-dense'
const group = (page:Page,key:string) => page.locator(`[data-today-section="${key}"]`)
const pageErrors = new WeakMap<Page,string[]>()
async function ready(page:Page) {
  await page.waitForFunction(()=>{const app=(document.querySelector('#__nuxt') as any)?.__vue_app__?.config.globalProperties.$nuxt;return app&&!app.isHydrating})
}
test.beforeEach(async ({page})=>{
  const errors:string[]=[];pageErrors.set(page,errors);page.on('pageerror',e=>errors.push(e.message))
  await page.route('https://**/*',r=>r.abort())
  await page.addInitScript(data=>{if(!localStorage.getItem('personal-ai-workspace:v1'))localStorage.setItem('personal-ai-workspace:v1',JSON.stringify(data))},createDenseToday())
  await page.goto('/');await ready(page)
})
test.afterEach(async({page})=>{expect(pageErrors.get(page)).toEqual([])})
test('dense Today renders all tasks, responsive columns and persisted independent groups',async({page},info)=>{
  const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message))
  await expect(group(page,'next').locator('[data-task-row]')).toHaveCount(1)
  const rows=group(page,'other').locator('[data-task-row]')
  await expect(rows).toHaveCount(23)
  await expect(group(page,'completed').locator('header')).toContainText('29')
  await expect(group(page,'completed').locator('[data-task-row]')).toHaveCount(0)
  const first=await rows.nth(0).boundingBox();const second=await rows.nth(1).boundingBox();const last=await rows.last().boundingBox()
  await info.attach('layout-measurements',{body:JSON.stringify({viewport:page.viewportSize(),first,second,last}),contentType:'application/json'})
  const coarse = await page.evaluate(()=>matchMedia('(pointer:coarse)').matches)
  const contentWidth = await page.locator('.suite-today .suite-content').evaluate(el=>el.clientWidth-parseFloat(getComputedStyle(el).paddingLeft)-parseFloat(getComputedStyle(el).paddingRight))
  expect(first!.height).toBeGreaterThanOrEqual(38);expect(first!.height).toBeLessThanOrEqual(coarse?50:46)
  if(contentWidth>=600){
    expect(first!.y).toBe(second!.y);expect(second!.x).toBeGreaterThan(first!.x)
  }else{expect(second!.y).toBeGreaterThan(first!.y);expect(second!.x).toBe(first!.x)}
  if(page.viewportSize()!.width>=1536 && page.viewportSize()!.height>=1024)expect(last!.y+last!.height).toBeLessThanOrEqual(page.viewportSize()!.height)
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
  const add=await page.locator('[data-quick-add]').boundingBox();const focus=await group(page,'next').boundingBox()
  expect(add!.y+add!.height).toBeLessThanOrEqual(focus!.y)
  await page.screenshot({path:info.outputPath('today-compact.png'),fullPage:false})
  await page.getByRole('button',{name:'收起其他待办',exact:true}).click()
  await page.getByRole('button',{name:'展开已完成',exact:true}).click()
  await expect(group(page,'completed').locator('[data-task-row]')).toHaveCount(29)
  await expect(group(page,'next').locator('[data-task-row]')).toHaveCount(1)
  await page.reload();await ready(page)
  await expect(group(page,'other').locator('[data-task-row]')).toHaveCount(0)
  await expect(group(page,'completed').locator('[data-task-row]')).toHaveCount(29)
  await page.getByRole('button',{name:'收起今日重点',exact:true}).click()
  await expect(group(page,'next').locator('[data-task-row]')).toHaveCount(0)
  expect(errors).toEqual([])
})
test('sort, filter, add, edit, complete, restore, delete and reload use the same persisted IDs',async({page})=>{
  const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message))
  const rows=group(page,'other').locator('[data-task-row]')
  const original=await rows.evaluateAll(els=>els.map(el=>el.getAttribute('data-task-id')))
  await page.getByLabel('任务排序',{exact:true}).selectOption('priority')
  expect(await rows.first().getAttribute('data-priority')).toBe('high')
  await page.getByLabel('任务排序',{exact:true}).selectOption('manual')
  expect(await rows.evaluateAll(els=>els.map(el=>el.getAttribute('data-task-id')))).toEqual(original)
  await page.getByLabel('筛选任务',{exact:true}).click()
  await page.getByLabel('筛选关键词',{exact:true}).fill('碳棉')
  await expect(rows).toHaveCount(1)
  await page.getByLabel('筛选关键词',{exact:true}).fill('')
  await expect(rows).toHaveCount(23)
  const input=page.getByLabel('快速添加任务',{exact:true})
  await input.fill('紧凑布局验收任务');await input.press('Enter')
  const row=page.locator('[data-task-row]').filter({hasText:'紧凑布局验收任务'})
  await expect(row).toBeVisible()
  const id=await row.getAttribute('data-task-id')
  await row.locator('summary').focus();await page.keyboard.press('Enter')
  await expect(row.locator('details')).toHaveAttribute('open','')
  await page.keyboard.press('Escape')
  await expect(row.locator('details')).not.toHaveAttribute('open','')
  await expect(row.locator('summary')).toBeFocused()
  await row.locator('.suite-task-title').click()
  const editor=page.locator('.task-editor')
  await editor.locator('[name="title"]').fill('紧凑布局已编辑')
  await editor.locator('[name="priority"]').selectOption('high')
  await editor.locator('[name="projectId"]').selectOption(createDenseToday().projects[0]!.id)
  await editor.locator('[name="dueDate"]').fill('261031')
  await editor.getByRole('button',{name:'保存更改',exact:true}).click()
  const edited=page.locator(`[data-task-id="${id}"]`)
  await expect(edited).toContainText('紧凑布局已编辑')
  await expect(edited).toHaveAttribute('data-priority','high')
  await expect(edited).toContainText('三维视频')
  await expect(edited).toContainText('2026-10-31')
  await edited.getByRole('button',{name:'完成 紧凑布局已编辑',exact:true}).click()
  await expect(group(page,'completed').locator('header')).toContainText('30')
  await page.getByRole('button',{name:'展开已完成',exact:true}).click()
  await edited.getByRole('button',{name:'恢复 紧凑布局已编辑',exact:true}).click()
  await expect(group(page,'completed').locator('header')).toContainText('29')
  await edited.locator('summary').click()
  await edited.getByRole('button',{name:'删除 紧凑布局已编辑',exact:true}).click()
  await page.getByRole('alertdialog').locator('[data-confirm-delete]').click()
  await expect(edited).toHaveCount(0)
  const saved=await page.evaluate(id=>JSON.parse(localStorage.getItem('personal-ai-workspace:v1')!).tasks.find((t:any)=>t.id===id),id)
  expect(saved.deletedAt).toBeTruthy();expect(saved.title).toBe('紧凑布局已编辑')
  expect(saved.priority).toBe('high');expect(saved.dueDate).toBe('2026-10-31')
  expect(saved.projectId).toBe(createDenseToday().projects[0]!.id)
  await page.reload();await ready(page);await expect(edited).toHaveCount(0)
  expect(errors).toEqual([])
})
