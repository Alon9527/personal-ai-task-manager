import { expect, test } from '@playwright/test'

async function ready(page: import('@playwright/test').Page) {
  await page.waitForFunction(() => {
    const app = (document.querySelector('#__nuxt') as any)?.__vue_app__?.config.globalProperties.$nuxt
    return app && !app.isHydrating
  })
}

test('Today delete supports cancel, undo, editor draft retention and trash restore', async ({ page }, info) => {
  await page.goto('/')
  await ready(page)
  await page.getByRole('button', { name: '新建任务', exact: true }).first().click()
  const editor = page.locator('.task-editor')
  await expect(editor.locator('[data-delete-task]')).toHaveCount(0)
  const title = '删除入口隔离验收任务'
  await editor.locator('[name="title"]').fill(title)
  await editor.getByRole('button', { name: '创建任务', exact: true }).click()
  const row = page.locator('.suite-task-row').filter({ hasText: title })
  await row.getByRole('button', { name: `删除 ${title}`, exact: true }).click()
  const confirm = page.getByRole('alertdialog')
  await expect(confirm).toContainText(title)
  await confirm.getByRole('button', { name: '取消', exact: true }).click()
  await expect(row).toBeVisible()
  await row.getByRole('button', { name: `删除 ${title}`, exact: true }).click()
  await confirm.locator('[data-confirm-delete]').click()
  await expect(row).toHaveCount(0)
  await page.locator('.undo-action').click()
  await expect(row).toBeVisible()

  await row.locator('.suite-task-title').click()
  await editor.locator('[name="title"]').fill('尚未保存的标题')
  await editor.locator('.dialog-header [data-delete-task]').click()
  await confirm.getByRole('button', { name: '取消', exact: true }).click()
  await expect(editor.locator('[name="title"]')).toHaveValue('尚未保存的标题')
  await page.screenshot({ path: info.outputPath('editor-delete-visible.png') })
  await editor.locator('[data-delete-task]').click()
  await confirm.locator('[data-confirm-delete]').click()
  await expect(editor).toHaveCount(0)
  await expect(row).toHaveCount(0)
  await page.goto('/trash')
  await ready(page)
  const trashRow = page.locator('[data-trash-task]').filter({ hasText: title })
  await expect(trashRow).toBeVisible()
  await trashRow.locator('[data-restore-task]').click()
  await expect(trashRow).toHaveCount(0)
  await page.goto('/')
  await ready(page)
  await expect(row).toBeVisible()
  await page.screenshot({ path: info.outputPath('task-list-delete-visible.png') })
})

test('calendar editor header deletes safely and task list exposes the same action', async ({ page }, info) => {
  await page.setViewportSize({ width: 1280, height: 900 })
  await page.goto('/calendar')
  await ready(page)
  await page.getByRole('button', { name: '新建任务', exact: true }).first().click()
  const editor = page.locator('.suite-inline-editor')
  await editor.locator('[name="title"]').fill('日历删除验收任务')
  await editor.getByRole('button', { name: '创建任务', exact: true }).click()
  const event = page.locator('.suite-calendar-event').filter({ hasText: '日历删除验收任务' })
  await event.click()
  const button = editor.locator('.dialog-header [data-delete-task]')
  await expect(button).toBeVisible()
  const overflow = await editor.locator('.dialog-header').evaluate(el => el.scrollWidth > el.clientWidth)
  expect(overflow).toBe(false)
  await page.screenshot({ path: info.outputPath('calendar-delete-visible.png') })
  await button.click()
  await page.getByRole('alertdialog').locator('[data-confirm-delete]').click()
  await expect(editor).toHaveCount(0)
  await expect(event).toHaveCount(0)
  await page.locator('.undo-action').click()
  await page.getByRole('button', { name: '列表', exact: true }).click()
  await expect(page.getByRole('button', { name: '删除 日历删除验收任务', exact: true })).toBeVisible()
})
